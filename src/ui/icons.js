export function iconSVG(name, size = 32) {
  const map = MAPS[name];
  if (!map) return '';
  let rects = '';
  for (let y = 0; y < map.length; y++) {
    for (let x = 0; x < map[y].length; x++) {
      const ch = map[y][x];
      if (ch === '.') continue;
      rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${COLORS[ch] || '#FFFFFF'}"/>`;
    }
  }
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}
