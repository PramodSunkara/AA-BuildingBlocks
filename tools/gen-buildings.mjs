const index = `// Generated by tools/gen-buildings.mjs. Order = catalogue order.
${out.map((o) => `import ${o.id.replace(/-(\w)/g, (_, c) => c.toUpperCase())} from './${o.id}.js';`).join('\n')}

export const BUILDINGS = [${out.map((o) => o.id.replace(/-(\w)/g, (_, c) => c.toUpperCase())).join(', ')}];
export const BUILDING_BY_ID = Object.fromEntries(BUILDINGS.map((b) => [b.id, b]));
`;
writeFileSync(new URL('../src/data/buildings/index.js', import.meta.url), index);
