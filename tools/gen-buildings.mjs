// Generates src/data/buildings/*.js (voxel blueprints). Run: node tools/gen-buildings.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import {
  COBBLE, STONE_BRICK, PLANKS, GLASS, ROOFING, FENCE, TORCH, LEAVES, WATER, WHEAT_1, PUMPKIN,
  FLOWER_RED, FLOWER_YELLOW, FLOWER_BLUE,
} from '../src/data/blocks.js';

class Model {
  constructor() { this.v = new Map(); }
  set(x, y, z, id) { if (id === 0) this.v.delete(`${x},${y},${z}`); else this.v.set(`${x},${y},${z}`, [x, y, z, id]); }
  box(x0, y0, z0, x1, y1, z1, id) {
    for (let y = y0; y <= y1; y++) for (let z = z0; z <= z1; z++) for (let x = x0; x <= x1; x++) this.set(x, y, z, id);
  }
  // vertical walls of a footprint (no top/bottom)
  walls(x0, y0, z0, x1, y1, z1, id) {
    for (let y = y0; y <= y1; y++) for (let z = z0; z <= z1; z++) for (let x = x0; x <= x1; x++) {
      if (x === x0 || x === x1 || z === z0 || z === z1) this.set(x, y, z, id);
    }
  }
  voxels() {
    return [...this.v.values()].sort((a, b) => a[1] - b[1] || a[2] - b[2] || a[0] - b[0]);
  }
}

const out = [];
function emit(meta, model) {
  const voxels = model.voxels();
  const size = [0, 0, 0];
  for (const [x, y, z] of voxels) { size[0] = Math.max(size[0], x + 1); size[1] = Math.max(size[1], y + 1); size[2] = Math.max(size[2], z + 1); }
  const rows = voxels.map((v) => `  [${v.join(', ')}],`).join('\n');
  const src = `// Generated by tools/gen-buildings.mjs. Do not edit by hand.
export default {
  id: '${meta.id}',
  name: '${meta.name}',
  level: ${meta.level},
  gemCost: ${meta.gemCost},
  rewardXp: ${meta.rewardXp},
  rewardGems: ${meta.rewardGems},
  size: [${size.join(', ')}],
  voxels: [
${rows}
  ],
};
`;
  mkdirSync(new URL('../src/data/buildings/', import.meta.url), { recursive: true });
  writeFileSync(new URL(`../src/data/buildings/${meta.id}.js`, import.meta.url), src);
  out.push({ id: meta.id, count: voxels.length, size });
}

// --- Well (3x3, ~14 blocks) ---
{
  const m = new Model();
  m.box(0, 0, 0, 2, 0, 2, COBBLE);
  m.set(1, 0, 1, WATER);
  m.set(0, 1, 1, FENCE); m.set(2, 1, 1, FENCE);
  m.box(0, 2, 1, 2, 2, 1, ROOFING);
  emit({ id: 'well', name: 'Well', level: 1, gemCost: 0, rewardXp: 250, rewardGems: 3 }, m);
}
